import { readFileSync, writeFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import type { ToolRequest, ToolResult } from "../src/tools/runner.ts";
import { rules } from "./helpers.ts";
import { argValue, checkTests, declare, fakeTools, ok, project } from "./tests-helpers.ts";

const PROFILE = `mode: set
example.com/app/calc.go:3.24,5.2 1 1
example.com/app/calc.go:7.24,9.2 1 0
example.com/app/api/api.pb.go:10.30,12.2 2 0
example.com/app/internal/mocks/store.go:5.40,7.2 1 0
`;

const FILES = {
  "svc/go.mod": "module example.com/app\n\ngo 1.26\n",
  "svc/calc.go": "package app\n",
  "svc/api/api.pb.go": "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage api\n",
  "svc/internal/mocks/store.go": "package mocks\n",
};

const COVER_FUNC = (total: string) =>
  `example.com/app/calc.go:3:\t\tAdd\t\t100.0%\nexample.com/app/calc.go:7:\t\tSub\t\t0.0%\ntotal:\t\t\t\t(statements)\t${total}\n`;

/** `go test` writes `profile` and answers with `test`; `go tool cover -func` answers `cover` and records its input. */
function goTools(profile: string | undefined, test: ToolResult, cover = ok(COVER_FUNC("50.0%"))) {
  const seen: string[] = [];
  const fake = fakeTools((req: ToolRequest) => {
    const args = req.args ?? [];
    if (args[0] === "test") {
      if (profile !== undefined) writeFileSync(argValue(req, "-coverprofile"), profile);
      return test;
    }
    seen.push(readFileSync(argValue(req, "-func"), "utf8"));
    return cover;
  });
  return { ...fake, seen };
}

const SVC = declare("svc/", "go");
const check = (tools: ReturnType<typeof goTools>["tools"], declaration = SVC) =>
  checkTests(project(declaration, FILES), tools, ["svc/calc.go", "svc/go.mod"]);

describe("Go tests", () => {
  it("runs go test with a cover profile, then go tool cover -func on it", async () => {
    const { tools, calls } = goTools(PROFILE, ok("ok  \texample.com/app\t0.01s"), ok(COVER_FUNC("85.0%")));
    expect((await check(tools)).findings).toEqual([]);
    expect(calls.map((c) => `${c.dir}:${c.tool} ${(c.args ?? [])[0] ?? ""} ${(c.args ?? []).at(-1) ?? ""}`)).toEqual([
      expect.stringMatching(/^svc\/:go test \.\/\.\.\.$/),
      expect.stringMatching(/^svc\/:go tool -func=.+$/),
    ]);
  });

  it("judges the total, leaving out generated files and mocks/", async () => {
    const { tools, seen } = goTools(PROFILE, ok(), ok(COVER_FUNC("50.0%")));
    const r = await check(tools);
    expect(seen).toEqual(["mode: set\nexample.com/app/calc.go:3.24,5.2 1 1\nexample.com/app/calc.go:7.24,9.2 1 0\n"]);
    expect(rules(r.findings)).toEqual(["error:coverage/lines"]);
    expect(r.findings[0]?.message).toBe("行覆蓋率 50% 低於門檻 80%");
  });

  it("applies the declared threshold", async () => {
    const declaration = declare("svc/", "go", '{coverage.lines: {value: 50, reason: "legacy", until: 2099-01-01}}');
    const r = await check(goTools(PROFILE, ok(), ok(COVER_FUNC("50.0%"))).tools, declaration);
    expect(rules(r.findings)).toEqual(["deviation:declaration/deviation"]);
  });

  it("passes when every covered block was left out", async () => {
    const { tools, calls } = goTools("mode: set\nexample.com/app/internal/mocks/store.go:5.40,7.2 1 0\n", ok());
    expect((await check(tools)).findings).toEqual([]);
    expect(calls).toHaveLength(1);
  });

  it("reports failing tests by name, apart from coverage", async () => {
    const out = "--- FAIL: TestAdd (0.00s)\n    calc_test.go:9: got 3\nFAIL\nFAIL\texample.com/app\t0.01s\nFAIL\n";
    const r = await check(goTools(PROFILE, ok(out, 1), ok(COVER_FUNC("40.0%"))).tools);
    expect(rules(r.findings)).toEqual(["error:test/failed", "error:coverage/lines"]);
    expect(r.findings[0]?.message).toBe("測試失敗：TestAdd");
  });

  it("reports a package that does not build as a failing test", async () => {
    const out = "# example.com/app\n./calc.go:4:2: undefined: x\nFAIL\texample.com/app [build failed]\nFAIL\n";
    const r = await check(goTools(undefined, ok(out, 1)).tools);
    expect(rules(r.findings)).toEqual(["error:test/failed", "error:coverage/no-report"]);
    expect(r.findings[0]?.message).toBe("測試失敗：example.com/app [build failed]");
  });

  it("reports a go test failure it cannot explain as a tool failure", async () => {
    const r = await check(goTools(undefined, ok("", 1, "go: cannot find main module")).tools);
    expect(rules(r.findings)).toEqual(["error:test/tool-failed"]);
  });

  it("reports go tool cover output without a total as a tool failure", async () => {
    const r = await check(goTools(PROFILE, ok(), ok("", 1, "cover: bad mode line")).tools);
    expect(rules(r.findings)).toEqual(["error:test/tool-failed"]);
  });
});
