import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { applyPlan, fileCategory, planChanges, renderPlan } from "../src/fix/plan.ts";

const dirs: string[] = [];
afterEach(() => {
  for (const d of dirs.splice(0)) rmSync(d, { recursive: true, force: true });
});

function repo(files: Record<string, string> = {}): string {
  const dir = mkdtempSync(join(tmpdir(), "devguard-fix-"));
  dirs.push(dir);
  for (const [name, text] of Object.entries(files)) {
    mkdirSync(dirname(join(dir, name)), { recursive: true });
    writeFileSync(join(dir, name), text);
  }
  return dir;
}

const read = (dir: string, name: string) => readFileSync(join(dir, name), "utf8");

describe("fileCategory (SPEC §9.2)", () => {
  it.each([
    ["pmd-ruleset.xml", "generated"],
    ["svc/config/pmd/ruleset.xml", "generated"],
    [".claude/rules/python.md", "generated"],
    [".mvn/settings.xml", "snippet"],
    ["pyproject.toml", "managed"],
    ["web/tsconfig.json", "managed"],
    [".golangci.yml", "managed"],
    [".prettierrc", "managed"],
    [".vscode/settings.json", "managed"],
    [".gitattributes", "managed"],
    ["pom.xml", "snippet"],
    ["build.gradle.kts", "snippet"],
    ["web/eslint.config.js", "snippet"],
    ["vitest.config.ts", "snippet"],
    ["../.m2/settings.xml", "user"],
    ["C:/Users/me/.npmrc", "user"],
  ])("%s is %s", (file, category) => {
    expect(fileCategory(file)).toBe(category);
  });
});

describe("planChanges / applyPlan", () => {
  it("edits only the managed keys of a structured file", async () => {
    const dir = repo({ "tsconfig.json": '{\n  // keep me\n  "compilerOptions": { "strict": false }\n}\n' });
    const plan = await planChanges(dir, [
      { op: "set", file: "tsconfig.json", path: ["compilerOptions", "strict"], value: true },
    ]);
    expect(renderPlan(plan)).toContain('+  "compilerOptions": { "strict": true }');
    await applyPlan(dir, plan);
    expect(read(dir, "tsconfig.json")).toBe('{\n  // keep me\n  "compilerOptions": { "strict": true }\n}\n');
  });

  it.each([
    ["generated by the CLI", { "pmd-ruleset.xml": "<!-- 由 CLI 產生 -->\n<ruleset name='devguard'/>" }],
    ["missing", {}],
    ["empty", { "pmd-ruleset.xml": "  \n" }],
  ])("regenerates a CLI-owned file that is %s whole, marked as generated by the CLI", async (_, files) => {
    const dir = repo(files);
    const content = '<?xml version="1.0"?>\n<ruleset name="devguard"/>\n';
    const plan = await planChanges(dir, [{ op: "generate", file: "pmd-ruleset.xml", content }]);
    await applyPlan(dir, plan);
    const text = read(dir, "pmd-ruleset.xml");
    expect(text.split("\n")[0]).toBe('<?xml version="1.0"?>');
    expect(text.split("\n")[1]).toContain("由 CLI 產生");
    expect(text).toContain('<ruleset name="devguard"/>');
  });

  it("never overwrites a CLI-owned file devguard did not generate, and prints the snippets to add (#100)", async () => {
    const own = "<ruleset name='ours'><!-- ours --></ruleset>\n";
    const dir = repo({ "pmd-ruleset.xml": own });
    const plan = await planChanges(dir, [
      { op: "generate", file: "pmd-ruleset.xml", content: "<ruleset name='devguard'/>\n" },
      {
        op: "snippet",
        file: "pmd-ruleset.xml",
        text: '加在 ruleset 底下：\n<rule ref="category/java/design.xml/CognitiveComplexity">\n</rule>',
      },
    ]);
    expect(plan.writes).toEqual([]);
    expect(renderPlan(plan)).toBe(
      [
        "pmd-ruleset.xml：這份檔案不是 devguard 產生的，不會覆寫；請自行加入以下內容",
        "    加在 ruleset 底下：",
        '    <rule ref="category/java/design.xml/CognitiveComplexity">',
        "    </rule>",
        "",
      ].join("\n"),
    );
    await applyPlan(dir, plan);
    expect(read(dir, "pmd-ruleset.xml")).toBe(own);
  });

  it("prints the whole generated content for a file devguard did not generate when no snippet says what to add", async () => {
    const dir = repo({ "config/pmd/ruleset.xml": "<ruleset name='ours'/>\n" });
    const plan = await planChanges(dir, [
      { op: "generate", file: "config/pmd/ruleset.xml", content: "<ruleset name='devguard'/>\n" },
    ]);
    expect(plan.writes).toEqual([]);
    expect(plan.printed).toEqual([
      { file: "config/pmd/ruleset.xml", category: "foreign", lines: ["（整份內容）\n<ruleset name='devguard'/>\n"] },
    ]);
  });

  it("only prints changes to build files and code-form config, and never writes them", async () => {
    const pom = "<project/>\n";
    const dir = repo({ "pom.xml": pom, "eslint.config.js": "export default [];\n" });
    const plan = await planChanges(dir, [
      { op: "snippet", file: "pom.xml", text: "<maven.compiler.release>17</maven.compiler.release>" },
      { op: "set", file: "eslint.config.js", path: ["rules", "complexity"], value: ["error", 10] },
    ]);
    expect(plan.writes).toHaveLength(0);
    const text = renderPlan(plan);
    expect(text).toContain("<maven.compiler.release>17</maven.compiler.release>");
    expect(text).toContain('rules.complexity: ["error",10]');
    await applyPlan(dir, plan);
    expect(read(dir, "pom.xml")).toBe(pom);
  });

  it("never writes user-level settings outside the repo", async () => {
    const dir = repo();
    const name = `devguard-user-${String(process.pid)}.gitignore`;
    const outside = join(dir, "..", name);
    const plan = await planChanges(dir, [{ op: "line", file: `../${name}`, value: "x=1" }]);
    expect(plan.writes).toHaveLength(0);
    expect(renderPlan(plan)).toContain("使用者層級");
    await applyPlan(dir, plan);
    expect(existsSync(outside)).toBe(false);
  });

  it("does not write a TOML file the edit would leave unparseable, and reports the edit instead (#105)", async () => {
    const text = "[tool]\nx = 1\n";
    const dir = repo({ "pyproject.toml": text });
    const plan = await planChanges(dir, [{ op: "set", file: "pyproject.toml", path: ["tool", "x", "y"], value: 1 }]);
    expect(plan.writes).toHaveLength(0);
    expect(renderPlan(plan)).toBe(
      "pyproject.toml：錯誤：修改後不是合法的 TOML，不會修改；請自行套用\n    tool.x.y: 1\n",
    );
    await applyPlan(dir, plan);
    expect(read(dir, "pyproject.toml")).toBe(text);
  });

  it("does not crash or write when an already invalid TOML file cannot be edited, and reports the edit (#105)", async () => {
    const text = "[tool\nx = 1\n";
    const dir = repo({ "pyproject.toml": text });
    const plan = await planChanges(dir, [{ op: "set", file: "pyproject.toml", path: ["tool", "y"], value: 1 }]);
    expect(plan.writes).toHaveLength(0);
    expect(renderPlan(plan)).toBe("pyproject.toml：錯誤：修改後不是合法的 TOML，不會修改；請自行套用\n    tool.y: 1\n");
    await applyPlan(dir, plan);
    expect(read(dir, "pyproject.toml")).toBe(text);
  });

  it("skips files already as the standard wants them", async () => {
    const dir = repo({ ".gitattributes": "* text=auto eol=lf\n" });
    const plan = await planChanges(dir, [{ op: "line", file: ".gitattributes", value: "* text=auto eol=lf" }]);
    expect(plan.writes).toHaveLength(0);
  });

  it("diffs CRLF files cleanly without reporting unchanged lines or emitting carriage returns", async () => {
    const dir = repo({ ".gitattributes": "*.png binary\r\n*.jpg binary\r\n" });
    const plan = await planChanges(dir, [{ op: "line", file: ".gitattributes", value: "* text=auto eol=lf" }]);
    const rendered = renderPlan(plan);
    expect(rendered).toContain(" *.png binary\n *.jpg binary\n+* text=auto eol=lf");
    expect(rendered).not.toContain("\r");
  });
});
