import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { applyPlan, fileCategory, planChanges, renderPlan } from "../src/fix/plan.ts";

const dirs: string[] = [];
afterEach(() => {
  for (const d of dirs.splice(0)) rmSync(d, { recursive: true, force: true });
});

function repo(files: Record<string, string> = {}): string {
  const dir = mkdtempSync(join(tmpdir(), "devguard-fix-"));
  dirs.push(dir);
  for (const [name, text] of Object.entries(files)) {
    mkdirSync(dirname(join(dir, name)), { recursive: true });
    writeFileSync(join(dir, name), text);
  }
  return dir;
}

const read = (dir: string, name: string) => readFileSync(join(dir, name), "utf8");

describe("fileCategory (SPEC §9.2)", () => {
  it.each([
    ["checkstyle.xml", "generated"],
    ["svc/config/pmd/ruleset.xml", "generated"],
    [".claude/rules/python.md", "generated"],
    [".mvn/settings.xml", "generated"],
    ["pyproject.toml", "managed"],
    ["web/tsconfig.json", "managed"],
    [".golangci.yml", "managed"],
    [".prettierrc", "managed"],
    [".vscode/settings.json", "managed"],
    [".gitattributes", "managed"],
    ["pom.xml", "snippet"],
    ["build.gradle.kts", "snippet"],
    ["web/eslint.config.js", "snippet"],
    ["vitest.config.ts", "snippet"],
    ["../.m2/settings.xml", "user"],
    ["C:/Users/me/.npmrc", "user"],
  ])("%s is %s", (file, category) => {
    expect(fileCategory(file)).toBe(category);
  });
});

describe("planChanges / applyPlan", () => {
  it("edits only the managed keys of a structured file", async () => {
    const dir = repo({ "tsconfig.json": '{\n  // keep me\n  "compilerOptions": { "strict": false }\n}\n' });
    const plan = await planChanges(dir, [
      { op: "set", file: "tsconfig.json", path: ["compilerOptions", "strict"], value: true },
    ]);
    expect(renderPlan(plan)).toContain('+  "compilerOptions": { "strict": true }');
    await applyPlan(dir, plan);
    expect(read(dir, "tsconfig.json")).toBe('{\n  // keep me\n  "compilerOptions": { "strict": true }\n}\n');
  });

  it("regenerates a CLI-owned file whole, marked as generated by the CLI", async () => {
    const dir = repo({ "checkstyle.xml": "<module name='Checker'/>" });
    const content = '<?xml version="1.0"?>\n<module name="Checker"/>\n';
    const plan = await planChanges(dir, [{ op: "generate", file: "checkstyle.xml", content }]);
    await applyPlan(dir, plan);
    const text = read(dir, "checkstyle.xml");
    expect(text.split("\n")[0]).toBe('<?xml version="1.0"?>');
    expect(text.split("\n")[1]).toContain("由 CLI 產生");
    expect(text).toContain('<module name="Checker"/>');
  });

  it("only prints changes to build files and code-form config, and never writes them", async () => {
    const pom = "<project/>\n";
    const dir = repo({ "pom.xml": pom, "eslint.config.js": "export default [];\n" });
    const plan = await planChanges(dir, [
      { op: "snippet", file: "pom.xml", text: "<maven.compiler.release>17</maven.compiler.release>" },
      { op: "set", file: "eslint.config.js", path: ["rules", "complexity"], value: ["error", 10] },
    ]);
    expect(plan.writes).toHaveLength(0);
    const text = renderPlan(plan);
    expect(text).toContain("<maven.compiler.release>17</maven.compiler.release>");
    expect(text).toContain('rules.complexity: ["error",10]');
    await applyPlan(dir, plan);
    expect(read(dir, "pom.xml")).toBe(pom);
  });

  it("never writes user-level settings outside the repo", async () => {
    const dir = repo();
    const name = `devguard-user-${String(process.pid)}.gitignore`;
    const outside = join(dir, "..", name);
    const plan = await planChanges(dir, [{ op: "line", file: `../${name}`, value: "x=1" }]);
    expect(plan.writes).toHaveLength(0);
    expect(renderPlan(plan)).toContain("使用者層級");
    await applyPlan(dir, plan);
    expect(existsSync(outside)).toBe(false);
  });

  it("skips files already as the standard wants them", async () => {
    const dir = repo({ ".gitattributes": "* text=auto eol=lf\n" });
    const plan = await planChanges(dir, [{ op: "line", file: ".gitattributes", value: "* text=auto eol=lf" }]);
    expect(plan.writes).toHaveLength(0);
  });
});
